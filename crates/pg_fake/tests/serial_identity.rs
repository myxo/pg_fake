#[test]
fn restores_owned_sequences_with_implicit_batch_ddl_rollback() {
    let db = Db::create();
    let mut session = db.create_session();

    assert_eq!(
        session
            .execute("CREATE TABLE transient_serial (id serial); SELECT 1 / 0")
            .unwrap_err()
            .sqlstate,
        SqlState::DivisionByZero
    );
    assert_eq!(
        session
            .query("SELECT nextval('transient_serial_id_seq')", &[])
            .unwrap_err()
            .sqlstate,
        SqlState::UndefinedTable
    );

    session
        .execute("CREATE TABLE restored_serial (id serial)")
        .unwrap();
    assert_eq!(
        session
            .query("SELECT nextval('restored_serial_id_seq')", &[])
            .unwrap()
            .rows,
        vec![vec![Value::Int8(1)]]
    );
    assert_eq!(
        session
            .execute("DROP TABLE restored_serial; SELECT 1 / 0")
            .unwrap_err()
            .sqlstate,
        SqlState::DivisionByZero
    );
    assert_eq!(
        session
            .query("SELECT nextval('restored_serial_id_seq')", &[])
            .unwrap()
            .rows,
        vec![vec![Value::Int8(2)]]
    );
}
